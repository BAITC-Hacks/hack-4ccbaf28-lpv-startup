const hash = (value: string) =>
  createHash("sha256").update(value).digest("hex");
const dates = Array.from({ length: 100 }, (_, day) =>
  new Date(Date.UTC(2026, 8, 23 + day)).toISOString().slice(0, 10),
);

function busyDates(id: string): string[] {
  const autumn = dates.filter((d) => d < "2026-12-01");
  const december = dates.filter((d) => d >= "2026-12-01");
  // A fixed seasonal stress case: December Saturdays are fully booked.
  const peak = december.filter(
    (d) => new Date(`${d}T12:00:00Z`).getUTCDay() === 6,
  );
  const choose = (days: string[], count: number) =>
    [...days]
      .sort((a, b) => hash(`${id}:${a}`).localeCompare(hash(`${id}:${b}`)))
      .slice(0, count);
  return [
    ...choose(autumn, 28),
    ...peak,
    ...choose(
      december.filter((d) => !peak.includes(d)),
      23 - peak.length,
    ),
  ].sort();
}

export function generateSyntheticCatalog(): Contractor[] {
  const output: Contractor[] = [];
  for (const [cityIndex, city] of cities.entries()) {
    for (const definition of definitions) {
      for (let i = 0; i < definition.count; i++) {
        const id = `LPV-SYN-${String(output.length + 1).padStart(3, "0")}`;
        const category = definition.category;
        const host = category === "Ведущий";
        const venue = category === "Банкетный зал" || category === "Ресторан";
        const photo = category === "Фотограф";
        const video = category === "Видеограф";
        const count = venue
          ? 30 + i * 25 + cityIndex * 10
          : photo
            ? 100 + i * 35 + cityIndex * 15
            : 12 + i * 2 + cityIndex;
        const detail = definition.details[i].replaceAll("{n}", String(count));
        const price =
          host && i >= 6
            ? 150000 + (i - 6) * 65000 + cityIndex * 10000
            : definition.base + i * definition.step + cityIndex * 5000;
        const hours = host
          ? i < 6
            ? 3 + (i % 3)
            : 6 + (i % 3)
          : venue
            ? 6 + (i % 3)
            : photo || video
              ? 2 + (i % 7)
              : 2 + (i % 3);
        let formats =
          i % 4 === 0
            ? ["корпоратив", "день рождения", "юбилей"]
            : i % 4 === 1
              ? ["корпоратив", "свадьба", "той"]
              : i % 4 === 2
                ? ["корпоратив", "конференция"]
                : ["корпоратив", "свадьба", "день рождения"];
        if (host && [3, 13].includes(i)) formats = ["день рождения", "юбилей"];
        if (host && i === 9) formats = ["той", "свадьба"];
        if (host && i === 11) formats = ["свадьба"];
        if (photo && i === 4) formats = ["свадьба", "день рождения", "юбилей"];
        if (photo && i === 6) formats = ["свадьба", "той"];
        if (photo && i === 7) formats = ["конференция", "корпоратив"];
        if (photo && i === 9) formats = ["той", "юбилей"];
        if (video && i === 3) formats = ["свадьба", "той"];
        if (video && i === 5) formats = ["конференция", "корпоратив"];
        output.push(
          contractorSchema.parse({
            id,
            anon_name:
              host || photo || video
                ? `${host ? names[i] : photoNames[i]} · ${category}`
                : `${category} «${["Кедр", "Сфера", "Атлас", "Маяк", "Орбита", "Сцена", "Панорама", "Ритм", "Диалог", "Квартал"][i]}»`,
            categories: [category],
            city,
            price_from_kzt: price,
            event_formats: formats,
            languages:
              host && i === 8
                ? ["русский", "казахский"]
                : category === "Лайв-бэнд" && i === 1
                  ? ["русский", "английский"]
                  : languages[(i + cityIndex) % languages.length],
            max_hours: hours,
            busy_dates: busyDates(id),
            description: `${detail}. Пакет рассчитан на срок до ${hours} ч; дополнительные услуги согласуются отдельно.`,
            synthetic: true,
            city_imputed: false,
            price_imputed: false,
          }),
        );
      }
    }
  }
  return output;
}
